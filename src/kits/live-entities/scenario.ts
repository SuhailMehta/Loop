/**
 * Tier 3 — a realistic demo scenario in central Bengaluru: a road race looping
 * Cubbon Park, with spectators circulating the surrounding venues.
 *
 * WHY THIS FILE EXISTS
 *
 * A load test and a product demo are different artefacts. 200 entities
 * scattered across a disc proves throughput, but it looks nothing like the
 * product — and a scene that fails visual inspection discredits the numbers
 * shown next to it.
 *
 * THREE CORRECTIONS THAT MATTERED
 *
 * 1. GEOMETRY IS REAL. Hand-guessed coordinates produced 3-point straight lines
 *    that cut through city blocks — the opposite of "following a road". Every
 *    polyline and polygon here comes from OpenStreetMap, the same source the
 *    basemap renders, so they align with the streets and parks on screen.
 *
 * 2. PEOPLE ARE INSIDE THE VENUE. An event happens *within* its zones. Most
 *    spectators walk inner circuits — the venue outline scaled toward its
 *    centroid — which is how crowds actually circulate.
 *
 * 3. THE RACE LOOPS. The course is a closed ring, so runners wrap around it
 *    continuously. Open routes reverse at their ends; a closed one must not, or
 *    runners visibly turn and run back into the field.
 *
 * The tier boundary holds: to the framework these are polylines, polygons and
 * strings. Nothing in src/geo knows this is a race in Bengaluru.
 */

