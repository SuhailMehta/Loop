/**
 * Bib numbers.
 *
 * THE POINT OF THIS FIELD IS PROVENANCE, NOT DECORATION.
 *
 * An earlier version tagged people `runner` vs `spectator` and coloured them
 * differently, which was a distinction the product had no way to know and the
 * user had no way to decode. A bib is different: it exists because the person
 * REGISTERED for the race, so the backend genuinely holds it, and it is the
 * thing a friend would actually ask about ("what's your bib?").
 *
 * So participation is derived from data the system really has, is surfaced as
 * text on tap rather than only as a hue, and is explained by an on-screen
 * legend. A visual encoding that cannot be decoded is decoration.
 */
const BIBS = RACER_NAMES.map((_, i) => String(101 + i));

