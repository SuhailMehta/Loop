/**
 * Tier 3 — venue geometry for the demo scenario.
 *
 * These are REAL polygons, taken from OpenStreetMap (the same source the
 * basemap is derived from) rather than hand-drawn boxes. That matters more than
 * it sounds: hand-authored rectangles sat in arbitrary places, so participants
 * were never inside them and the scene read as incoherent. Real venue outlines
 * line up with the buildings and parks on the basemap, so the zones look like
 * places rather than annotations.
 *
 * The event: a gathering across the Cubbon Park cluster in central Bengaluru.
 *
 * `zoneKind` is opaque to the framework — only the style expression reads it.
 */

export interface ZoneFeature {
  type: 'Feature';
  id: string;
  geometry: { type: 'Polygon'; coordinates: number[][][] };
  properties: { name: string; zoneKind: string; selected: boolean };
}

